CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pg_trgm";

CREATE SCHEMA IF NOT EXISTS platform;
CREATE SCHEMA IF NOT EXISTS identity;
CREATE SCHEMA IF NOT EXISTS crm;
CREATE SCHEMA IF NOT EXISTS finance;
CREATE SCHEMA IF NOT EXISTS audit;

DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'crm_owner') THEN
        CREATE ROLE crm_owner WITH NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
    END IF;

    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'crm_migrator') THEN
        CREATE ROLE crm_migrator WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT;
        GRANT crm_owner TO crm_migrator;
    END IF;

    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'crm_app') THEN
        CREATE ROLE crm_app WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
    END IF;

    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'platform_app') THEN
        CREATE ROLE platform_app WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
    END IF;
END
$$;

ALTER SCHEMA platform OWNER TO crm_owner;
ALTER SCHEMA identity OWNER TO crm_owner;
ALTER SCHEMA crm OWNER TO crm_owner;
ALTER SCHEMA finance OWNER TO crm_owner;
ALTER SCHEMA audit OWNER TO crm_owner;

GRANT USAGE ON SCHEMA identity, crm, audit TO crm_app;
GRANT USAGE ON SCHEMA platform, identity, audit TO platform_app;
